import { parse } from 'yaml';
import { BADGES } from '../src/achievements/catalog';
import { MASTERIES, OPENING_MASTERIES, TACTICAL_MASTERIES, ENDGAME_MASTERIES } from '../src/achievements/mastery-policy';

const sources = import.meta.glob<string>('../../data/achievements/{badges,masteries}/**/*.yml', {
  query: '?raw', import: 'default', eager: true,
});
const origins = new Map<string, string>();
for (const [path, source] of Object.entries(sources)) {
  const parsed = parse(source);
  for (const entry of Array.isArray(parsed) ? parsed : [parsed]) {
    if (origins.has(entry.id)) throw new Error(`Duplicate achievement definition: ${entry.id}`);
    origins.set(entry.id, path.replace('../../', ''));
  }
}

const banner = '<!-- Generated by pnpm achievements:generate from the runtime catalogs. Do not edit. -->\n';
const cell = (text: string) => text.replaceAll('|', '\\|').replace(/[\r\n]+/g, ' ');
interface Entry { id: string; name: string; description?: string; category?: string; subcategory?: string }
function table(title: string, entries: Entry[], includeDescriptions = false) {
  let output = `${banner}\n# ${title}\n\n[Implemented achievement index](../implemented-achievements.md).\n\n`;
  if (includeDescriptions)
    output += 'Descriptions come from the active badge definitions. See [qualification details](../badge-rules.md) for processing requirements and source-data limits.\n\n';
  const groups = new Map<string, Entry[]>();
  for (const entry of entries) {
    const origin = origins.get(entry.id);
    if (!origin) throw new Error(`No YAML source for active achievement ${entry.id}`);
    groups.set(origin, [...(groups.get(origin) ?? []), entry]);
  }
  for (const [origin, group] of [...groups].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)) {
    const first = group[0];
    output += `## ${first.category ?? 'Masteries'} / ${first.subcategory ?? first.name}\n\n`;
    output += `Definition: [${origin.split('/').at(-1)}](../../../${origin}).\n\n`;
    output += includeDescriptions ? '| Achievement | ID | When you get it |\n| --- | --- | --- |\n' : '| Achievement | ID |\n| --- | --- |\n';
    output += group.map(entry => {
      if (includeDescriptions && !entry.description?.trim()) throw new Error(`Missing badge description: ${entry.id}`);
      return `| ${cell(entry.name)} | \`${entry.id}\` |${includeDescriptions ? ` ${cell(entry.description!)} |` : ''}`;
    }).join('\n') + '\n\n';
  }
  return output.trimEnd() + '\n';
}

export function achievementReference(): Record<string, string> {
  const caro = MASTERIES.filter(entry => origins.get(entry.id)?.endsWith('/caro-kann-defense.yml'));
  const other = MASTERIES.filter(entry => !caro.includes(entry));
  const opening = OPENING_MASTERIES;
  const tactical = TACTICAL_MASTERIES;
  const endgame = ENDGAME_MASTERIES;
  const files: Record<string, string> = {
    'implemented-achievements/badges.md': table(`Implemented badges (${BADGES.length})`, BADGES, true),
    'implemented-achievements/masteries.md': table(`Implemented masteries outside Caro-Kann (${other.length})`, other),
    'implemented-achievements/caro-kann-white.md': table('Implemented Caro-Kann masteries: White', caro.filter(entry => entry.color === 'white')),
    'implemented-achievements/caro-kann-black.md': table('Implemented Caro-Kann masteries: Black', caro.filter(entry => entry.color === 'black')),
  };
  files['implemented-achievements.md'] = `${banner}
# Implemented achievements

This is the authoritative implementation inventory for the game designer and
contributors. Its enumerated lists are generated from the same runtime catalogs
used by the application: [BADGES](../../web/src/achievements/catalog.ts) and
[MASTERIES](../../web/src/achievements/mastery-policy.ts). YAML or JSON definitions
outside those catalogs do not establish implementation.

“Implemented” means the achievement has an active awarding path in
[collection processing](../../web/src/achievements/collection.ts). It does not mean
every game can earn it, that all reference data is available, or that its tuning
is final. See the linked qualification references for prerequisites and limits.
In particular, the opening book currently lacks outcome counts, and insufficient
engine or source evidence can leave awards unconfirmed.

## Implemented list

| Family | Registered definitions or tracks | Complete list | Qualification |
| --- | ---: | --- | --- |
| Badges | ${BADGES.length} | [All badges](implemented-achievements/badges.md) | [Badge rules](badge-rules.md), [board events](browser-proof.md#active-board-event-badges) |
| Tactical masteries | ${tactical.length} | [Masteries outside Caro-Kann](implemented-achievements/masteries.md) | [Tactical rules](tactical-masteries.md) |
| Opening masteries | ${opening.length} | [Other openings](implemented-achievements/masteries.md), [Caro-Kann White](implemented-achievements/caro-kann-white.md), [Caro-Kann Black](implemented-achievements/caro-kann-black.md) | [Opening rules](opening-masteries.md) |
| Endgame masteries | ${endgame.length} | [Masteries outside Caro-Kann](implemented-achievements/masteries.md) | [Endgame rules](endgame-masteries.md) |

There are **${BADGES.length} badge definitions** and **${MASTERIES.length} mastery tracks**.
Badge tiers and mastery levels are progression within those definitions, not
additional achievements. White and Black opening tracks have distinct IDs and
are counted separately. Every linked row includes its exact runtime ID and
its YAML source.

## Checkmate scraps

Checkmate-notation scraps are also implemented. Their identities are generated
from canonical mating SAN, so they have no fixed enumerated catalog. Actual
checkmates earn real scraps; validated engine finishes can earn virtual scraps.
Real and virtual are states of the same collectible, with real occurrences
tracked by color. See the [collection implementation](../../web/src/achievements/collection.ts)
and [checkmate scrap rules](../../design/mechanics/checkmate-scraps.md).

## Outside the implemented list

The [legacy opening drafts](../../data/achievements/mastery.json),
[named scrap drafts](../../data/achievements/scraps/), and
[story nodes](../../data/achievements/story.json) are not active achievements.
The [design implementation map](../../design/planning/achievement-implementation.md)
retains their open mechanics and planned work; it is not a second implementation
inventory. The [Caro-Kann granularity review](../../design/content/caro-kann-masteries.md)
groups opening identities and aliases for design review.

## Keep this inventory current

Change the runtime catalog, awarding implementation, and relevant tests first.
Run \`pnpm achievements:generate\` to regenerate this index and its tables.
Run \`pnpm achievements:check\` to check freshness without writing files.
The browser unit suite also checks freshness, exact membership, and unique IDs;
\`pnpm docs:check\` validates document sizes and links. Do not update generated
counts or rows by hand.
`;
  return files;
}
