import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';

const check = process.argv.includes('--check');
const webRoot = fileURLToPath(new URL('..', import.meta.url));
const reference = resolve(webRoot, '../docs/reference');
const server = await createServer({ root: webRoot, appType: 'custom', server: { middlewareMode: true }, logLevel: 'error' });
try {
  const { achievementReference } = await server.ssrLoadModule('/scripts/achievement-reference.ts');
  const files = achievementReference();
  const existing = (await readdir(resolve(reference, 'implemented-achievements')).catch(error => {
    if (error.code === 'ENOENT') return [];
    throw error;
  })).map(name => `implemented-achievements/${name}`);
  const stale = [];
  for (const [name, content] of Object.entries(files)) {
    const path = resolve(reference, name);
    const before = await readFile(path, 'utf8').catch(error => {
      if (error.code === 'ENOENT') return undefined;
      throw error;
    });
    if (before === content) continue;
    stale.push(name);
    if (!check) { await mkdir(dirname(path), { recursive: true }); await writeFile(path, content); }
  }
  for (const name of existing.filter(name => !(name in files))) {
    stale.push(name);
    if (!check) {
      const path = resolve(reference, name);
      if (!(await readFile(path, 'utf8')).startsWith('<!-- Generated by pnpm achievements:generate'))
        throw new Error(`Unexpected authored file ${name}; refusing to remove it.`);
      await rm(path);
    }
  }
  if (check && stale.length) throw new Error(`Achievement reference is stale: ${stale.join(', ')}. Run pnpm achievements:generate.`);
  console.log(`${check ? 'Checked' : 'Generated'} ${Object.keys(files).length} achievement reference pages from the runtime catalogs.`);
} finally { await server.close(); }
