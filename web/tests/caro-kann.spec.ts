import { expect, test } from '@playwright/test';

test('Caro-Kann analysis collects its named branches and supports search, replay, reload, and color correction', async ({ page }, info) => {
  await page.goto('/review');
  await expect(page.getByTestId('status')).toHaveAttribute('data-state', 'ready');
  await page.getByRole('link', { name: 'Achievements', exact: true }).click();
  await expect(page.locator('.mastery-grid article')).toHaveCount(3);
  await expect(page.getByRole('navigation', { name: 'Mastery pages' })).toHaveCount(0);
  await page.getByLabel('Search masteries', { exact: true }).fill('Caro-Kann');
  await expect(page.locator('.mastery-grid article')).toHaveCount(0);
  await expect(page.getByText('No masteries match this search.', { exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Game review', exact: true }).click();
  const summary = page.locator('summary').filter({ hasText: 'Import a PGN or try an example' });
  if (!(await summary.locator('..').evaluate(element => element.hasAttribute('open')))) await summary.click();
  await page.getByRole('button', { name: 'Caro-Kann example', exact: true }).click();
  await page.getByLabel('I played as').selectOption('black');
  await expect(page.getByTestId('opening-status')).toContainText('analyze the complete game');
  await page.getByRole('button', { name: 'Analyze this game', exact: true }).click();
  await expect(page.getByTestId('status')).toHaveAttribute('data-state', 'complete', { timeout: 150000 });
  await expect(page.getByTestId('opening-status')).toContainText('Caro-Kann Defense: Advance Variation, Short Variation');
  await page.getByRole('link', { name: 'Achievements', exact: true }).click();
  await expect(page.getByTestId('mastery_caro_kann_black')).toHaveCount(0);
  await page.getByRole('link', { name: 'Game review', exact: true }).click();
  await page.getByRole('button', { name: 'Collect rewards', exact: true }).click();
  await expect(page.getByTestId('reward-reveal')).toContainText('The Iron Wall');
  await expect(page.getByTestId('reward-reveal')).toContainText('Short Variation (Black)');
  await page.getByRole('button', { name: 'Last position', exact: true }).click();
  const replay = page.getByTestId('replay-mastery_caro_kann_advance_variation_short_variation_black');
  const earned = await replay.innerText();
  expect(earned).not.toContain('+0 XP');
  await expect(page.getByTestId('replay-mastery_caro_kann_advance_variation_tal_variation_black')).toHaveCount(0);
  await page.getByRole('button', { name: 'First position', exact: true }).click();
  await expect(replay).toContainText('+0 XP');
  await page.getByRole('link', { name: 'Achievements', exact: true }).click();
  await expect(page.getByRole('navigation', { name: 'Mastery pages' })).toHaveCount(0);
  await page.getByLabel('Search masteries', { exact: true }).fill('Short Variation');
  await expect(page.locator('.mastery-grid article')).toHaveCount(1);
  const black = page.getByTestId('mastery_caro_kann_advance_variation_short_variation_black');
  const white = page.getByTestId('mastery_caro_kann_advance_variation_short_variation_white');
  await expect(black).toContainText('Playing Caro-Kann Defense: Advance Variation, Short Variation as Black');
  await expect(white).toHaveCount(0);
  const total = await black.getByTestId('mastery_caro_kann_advance_variation_short_variation_black-total-xp').innerText();
  expect(total).not.toBe('0 XP');
  await black.locator('summary').click();
  await expect(black.getByTestId('opening-history')).toBeVisible();
  await black.screenshot({ path: info.outputPath('caro-kann-short.png') });
  await page.reload();
  await page.getByLabel('Search masteries', { exact: true }).fill('Short Variation');
  await expect(black.getByTestId('mastery_caro_kann_advance_variation_short_variation_black-total-xp')).toHaveText(total);
  await black.locator('summary').click();
  await black.getByRole('button', { name: 'Replay opening', exact: true }).click();
  await page.getByRole('button', { name: 'Collect rewards', exact: true }).click();
  await expect(page.getByTestId('reward-reveal')).toContainText('No progress was counted twice.');
  await page.getByLabel('I played as').selectOption('white');
  await page.getByRole('button', { name: 'Collect rewards', exact: true }).click();
  await expect(page.getByTestId('reward-reveal')).toContainText('The Wall Breaker');
  await page.getByRole('link', { name: 'Achievements', exact: true }).click();
  await page.getByLabel('Search masteries', { exact: true }).fill('Short Variation');
  await expect(black).toHaveCount(0);
  await expect(white).toContainText('Facing Caro-Kann Defense: Advance Variation, Short Variation as White');
  await expect(white.getByTestId('mastery_caro_kann_advance_variation_short_variation_white-total-xp')).not.toHaveText('0 XP');
  await page.getByLabel('Language', { exact: true }).selectOption('de');
  await page.getByLabel('Meisterschaften suchen', { exact: true }).fill('Short-Variante');
  await expect(white).toContainText('Gegen Caro-Kann-Verteidigung: Vorstoßvariante, Short-Variante mit Weiß spielen');
  await page.getByLabel('Meisterschaften suchen', { exact: true }).fill('unknown-branch');
  await expect(page.getByText('Keine Meisterschaften entsprechen dieser Suche.', { exact: true })).toBeVisible();
});
